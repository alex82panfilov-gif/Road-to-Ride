export function sellerScript(model: Model): string {
  const specific = model.risks
    .slice(0, 2)
    .map((risk) => risk.howToCheck)
    .join(" ");
  return [
    `Здравствуйте! Интересует ${model.brand} ${model.model}, ${model.generation}.`,
    "Сколько собственников в ПТС и кто продаёт — собственник или родственник?",
    "Когда меняли масло в автомате и можно ли посмотреть заказ-наряд?",
    "Можно приехать с толщиномером и заехать на диагностику до задатка?",
    specific,
  ]
    .filter(Boolean)
    .join(" ");
}
