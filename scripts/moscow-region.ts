export function normalizeCity(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/^(город|г\.?)\s+/i, "")
    .replace(/\s+/g, " ");
}

/** Города Московской области, уже в нижнем регистре и без «ё». */
export const MOSCOW_OBLAST_CITIES: ReadonlySet<string> = new Set(OBLAST_NAMES.map(normalizeCity));

const MOSCOW_CITIES: ReadonlySet<string> = new Set(MOSCOW_NAMES.map(normalizeCity));

export function isMoscowRegionCity(raw: string): boolean {
  const city = normalizeCity(raw);
  return city !== "" && (MOSCOW_CITIES.has(city) || MOSCOW_OBLAST_CITIES.has(city));
}
